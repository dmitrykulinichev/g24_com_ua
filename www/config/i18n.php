<?php

/*
|--------------------------------------------------------------------------
| Мови лендінгу (app/I18n)
|--------------------------------------------------------------------------
| Основна мова — на корені адреси (/features), інші — з префіксом (/en/features).
| `public` — мова відкрита відвідувачам: є в перемикачі, hreflang і мапі сайту. Закриту мову видно лише
| з LANDING_LOCALES_PREVIEW=true (для перекладу й перевірки); інакше її адреси — 404. Так основу можна
| викласти, поки переклади не готові, і відкривати мови поступово (LANDING_LOCALES).
| Тексти — lang/{мова}.php; немає перекладу → основна мова.
*/

$public = array_filter(array_map('trim', explode(',', $_ENV['LANDING_LOCALES'] ?? 'uk')));

return [
    'default' => 'uk',

    'locales' => [
        'uk' => ['name' => 'Українська', 'short' => 'UA', 'hreflang' => 'uk', 'og' => 'uk_UA'],
        'en' => ['name' => 'English',    'short' => 'EN', 'hreflang' => 'en', 'og' => 'en_US'],
        'ru' => ['name' => 'Русский',    'short' => 'RU', 'hreflang' => 'ru', 'og' => 'ru_RU'],
    ],

    // Відкриті мови (основна — завжди)
    'public' => array_values(array_unique(array_merge(['uk'], $public))),

    // Адреси, вміст яких перекладено (тексти зі словників lang/*): лише для них canonical поточною мовою,
    // hreflang і мовні адреси в мапі сайту. Решта (блог, документація — поки) під /en|/ru показує
    // український вміст із canonical на українську адресу — без дублів для пошуковиків.
    // «/docs/*» — адреса й усе під нею. Відкрили переклад сторінки — додати сюди.
    // Відкрили сторінку — додати її розділ словника в tests/I18nTest.php («перекладена сторінка — усі тексти…»).
    'localized_paths' => ['/', '/contacts'],

    'preview' => filter_var($_ENV['LANDING_LOCALES_PREVIEW'] ?? false, FILTER_VALIDATE_BOOLEAN),
];
